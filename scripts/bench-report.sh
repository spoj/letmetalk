#!/bin/bash
# Writes trial/1-bench-local.md from the raw JSON lines in trial/bench-local/. bench-local.sh runs it at the end.
set -eu
cd "$(dirname "$0")/.."
OUT=trial/bench-local
WEB=target/bench-web
RUNS=$(ls "$OUT" | grep -c '^native-native-.*jsonl$')
{
  echo "# Bench on this machine"
  echo
  echo "Generated by \`scripts/bench-local.sh\` at $(git rev-parse --short HEAD) on $(date -u +%F), $RUNS runs per pair."
  echo "Raw JSON lines are in \`$OUT/\`, one file per pair and run; each file starts with the load before its run."
  echo
  echo "- Machine: $(nproc) CPUs, kernel $(uname -r), shared with other agents' work."
  echo "- Load average (1, 5, 15 min) at the start of each run:"
  for f in "$OUT"/*.jsonl; do
    echo "  - $(basename "$f" .jsonl): $(grep -ho 'loadavg_start":"[^"]*' "$f" | cut -d'"' -f3)"
  done
  echo "- \`net.core.rmem_max\`: $(sysctl -n net.core.rmem_max) bytes."
  echo "- Chromium $("${CHROME:-/opt/google/chrome/chrome}" --version 2>/dev/null)"
  echo "- Crates: $(for c in webrtc snow chacha20poly1305 iroh; do awk -v c="$c" '$0 == "name = \"" c "\"" {getline; print c " " $3}' Cargo.lock; done | tr -d '"' | paste -sd, - | sed 's/,/, /g')."
  echo "- wasm: \`letmetalk_bench.wasm\` is $(stat -c %s target/wasm32-unknown-unknown/release/letmetalk_bench.wasm) bytes;"
  echo "  wasm-bindgen's output $(stat -c %s "$WEB/pkg/letmetalk_bench_bg.wasm") bytes, $(gzip -9c "$WEB/pkg/letmetalk_bench_bg.wasm" | wc -c) gzipped."
  echo
  echo "## Medians of $RUNS runs"
  echo
  python3 scripts/bench-summary.py "$OUT"
} > trial/1-bench-local.md
